class VacuumChargeFromCY3:
    """
    Заряды q из структуры вакуума SU(26) и геометрии CY₃.
    
    Использует:
        C.H11 = 6, C.H21 = 9
        MasterPolynomial.n_poly(2) = 4
    """
    
    # Числа Ходжа
    H11 = C.H11
    H21 = C.H21
    
    # Мастер-полином
    N2 = MasterPolynomial.n_poly(2)  # = 4
    
    # Пороги
    T = H11 + N2              # = 10
    PHI_THRESHOLD = H11 - 1   # = 5
    
    # Φ-спектры в вакууме
    PHI_SPECTRA = {
        'up':     [3, 3],
        'down':   [3, 3],
        'lepton': [10, 10],
    }
    
    # IDX CY₃
    IDX = {
        'up':     [0, 1, 19],
        'down':   [0, 1, 5],
        'lepton': [0, 8, 25],
    }
    
    # Эталонные заряды
    REFERENCE = {
        'up':     [0, 4, 8],
        'down':   [3, 6, 8],
        'lepton': [3, 5, 9],
    }
    
    def _cumulative(self, phi: List[int]) -> List[int]:
        """Кумулятивные размеры блоков Φ."""
        result = [0]
        total = 0
        for s in phi:
            total += s
            result.append(total)
        return result[:3]
    
    def _get_case(self, phi_size: int, idx2: int) -> str:
        """Определение случая формулы."""
        if phi_size > self.PHI_THRESHOLD:
            return 'complex'
        elif idx2 > self.T:
            return 'linear'
        else:
            return 'power'
    
    def _get_params(self, case: str) -> Dict[str, float]:
        """Параметры A, p, B, C, D для случая."""
        if case == 'complex':
            return {
                'A': (self.H11 - 1) / self.H21,
                'p': 1.0,
                'B': (self.H21 + 1) / self.H21,
                'C': -(self.H11 - 1),
                'D': self.H11 * (self.H11 - 1) / self.H21,
            }
        elif case == 'linear':
            return {
                'A': (self.H21 - 1) / self.H11,
                'p': 1.0,
                'B': 0.0, 'C': 0.0, 'D': 0.0,
            }
        else:  # power
            return {
                'A': (self.H21 + 1) / (self.H11 + 1),
                'p': (self.H11 - 1) / (self.H11 + 1),
                'B': 0.0, 'C': 0.0,
                'D': (self.H11 - 1) * (self.H11 - 2) / (self.H11 + 1),
            }
    
    def compute_charges(self, sector: str) -> List[float]:
        """
        Заряды q для сектора из структуры вакуума и CY₃.
        
        Параметры:
            sector: 'up', 'down', 'lepton'
        """
        phi = self.PHI_SPECTRA[sector]
        idx2 = self.IDX[sector][2]
        case = self._get_case(phi[0], idx2)
        params = self._get_params(case)
        cum = self._cumulative(phi)
        
        return [
            params['A'] * cum[i] ** params['p']
            + params['B'] * i**2
            + params['C'] * i
            + params['D']
            for i in range(3)
        ]
    
    def verify(self) -> Dict:
        """Проверка зарядов против эталона."""
        results = {}
        all_match = True
        
        for sector in ['up', 'down', 'lepton']:
            q = self.compute_charges(sector)
            q_rounded = [round(x) for x in q]
            reference = self.REFERENCE[sector]
            match = (q_rounded == reference)
            if not match:
                all_match = False
            
            results[sector] = {
                'q_exact': q,
                'q_rounded': q_rounded,
                'reference': reference,
                'match': match,
                'phi': self.PHI_SPECTRA[sector],
                'idx2': self.IDX[sector][2],
                'case': self._get_case(
                    self.PHI_SPECTRA[sector][0],
                    self.IDX[sector][2]
                ),
            }
        
        return {
            'sectors': results,
            'all_match': all_match,
            'h11': self.H11,
            'h21': self.H21,
            'chi': 2 * (self.H11 - self.H21),
            'n_gen': abs(2 * (self.H11 - self.H21)) // 2,
            'T': self.T,
            'phi_threshold': self.PHI_THRESHOLD,
            'n2': self.N2,
        }
    
    def get_full_report(self) -> Dict:
        """Полный отчёт."""
        return self.verify()


