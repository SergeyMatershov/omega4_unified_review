@lru_cache(maxsize=1)
def _compute_eps_fn_exact_str() -> str:
    """
    Вычислить ε_FN = dim_q(Λ¹) / dim_q(Λ³) с 50 знаками через mpmath.

    Возвращает строку (50 знаков), чтобы не терять точность при float().

    ТРЕБУЕТ mpmath. Если его нет — падает с RuntimeError.
    """
    try:
        import mpmath as mp
    except ImportError:
        raise RuntimeError(
            "EPS_FN требует mpmath для точного вычисления. "
            "Установите: pip install mpmath"
        )

    mp.mp.dps = 50

    def dim_q(i, n=26, k=3):
        lambda_w = [1 if a <= i else 0 for a in range(1, n + 1)]
        rho = [mp.mpf(n - 2 * a - 1) / 2 for a in range(1, n + 1)]
        m = [lambda_w[a - 1] + rho[a - 1] for a in range(1, n + 1)]
        N_eff = k + n

        log_NUM = mp.mpf(0)
        for a in range(n):
            for b in range(a + 1, n):
                arg = mp.pi * (m[a] - m[b]) / N_eff
                log_NUM += mp.log(abs(mp.sin(arg)))

        log_N_norm = mp.mpf(0)
        for a in range(n):
            for b in range(a + 1, n):
                arg = mp.pi * (b - a) / N_eff
                log_N_norm -= mp.log(abs(mp.sin(arg)))

        return mp.exp(log_NUM + log_N_norm)

    value = dim_q(1) / dim_q(3)
    return mp.nstr(value, 50)
