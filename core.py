#
# КАК РАБОТАЕТ:
#   1. Есть класс ConstantsRegistry — простое key-value хранилище.
#   2. Есть глобальный REGISTRY.
#   3. Есть функция _auto_collect_constants(instance, registry),
#      которая автоматически собирает ВСЕ поля @dataclass и ВСЕ
#      свойства @property из экземпляра класса Constants.
#   4. Есть словарь CONSTANT_METADATA, где можно задать
#      уровень/единицу/комментарий для конкретных констант.
#
# ПОРЯДОК РАБОТЫ:
#   1. Сначала ручные REGISTRY.register(...) — они дают детали.
#   2. Потом _auto_collect_constants(C, REGISTRY) — дополняет то,
#      чего нет, и НЕ перезаписывает уже зарегистрированное.
# ============================================================================


class ConstantsRegistry:
    """Единый реестр констант Ω⁴-UNIFIED."""

    def __init__(self):
        self._registry: Dict[str, Dict[str, Any]] = {}

    def register(
        self,
        name: str,
        value: Any,
        *,
        unit: str = '',
        level: Any = 'LOST',
        formula: Any = None,
        formula_repr: str = '',
        source: str = 'auto',
        comment: str = '',
        depends_on: Optional[List[str]] = None,
        derives_to: Optional[List[str]] = None,
        status: str = '✅ auto',
        overwrite: bool = False,
    ) -> None:
        """
        Зарегистрировать константу.

        Параметры:
            name:          имя константы (например, 'CHI')
            value:         значение
            unit:          единица измерения (например, 'ГэВ')
            level:         уровень иерархии ('OBS' | 0 | 1 | 2 | 3 | 'CP' | 'LOST')
                           ВАЖНО: int-значения (0, 1, 2, 3) автоматически
                           нормализуются в строки ('0', '1', '2', '3'),
                           чтобы устранить несогласованность типов в реестре.
            formula:       callable без аргументов, возвращающий значение
            formula_repr:  ТЕКСТОВОЕ представление формулы (например, "M_W * H11 / 25")
            source:        источник (например, 'PDG 2024', 'auto')
            comment:       комментарий
            depends_on:    список констант, от которых зависит
            derives_to:    список констант, которые зависят от данной
            status:        статус (✅ / 🟡 / ❌ / ⚠️ / 📜)
            overwrite:     если False — не перезаписывать существующую запись
        """
        if not overwrite and name in self._registry:
            return

        # ── НОРМАЛИЗАЦИЯ LEVEL (v79.0.10) ──
        # Приводим level к строке: 0 → '0', 1 → '1', 2 → '2', 3 → '3'.
        # Это устраняет несогласованность int vs str в автогеноме
        # (аудит audit_genome.py показал 216 записей с int level).
        # Специальные уровни ('OBS', 'CP', 'LOST') — уже строки, не трогаем.
        if isinstance(level, int):
            level = str(level)

        self._registry[name] = {
            'value': value,
            'unit': unit,
            'level': level,
            'formula': formula,
            'formula_repr': formula_repr,
            'source': source,
            'comment': comment,
            'depends_on': depends_on or [],
            'derives_to': derives_to or [],
            'status': status,
        }

    def get(self, name: str) -> Optional[Dict[str, Any]]:
        return self._registry.get(name)

    def all(self) -> Dict[str, Dict[str, Any]]:
        return dict(self._registry)

    def __len__(self) -> int:
        return len(self._registry)

    def __contains__(self, name: str) -> bool:
        return name in self._registry


