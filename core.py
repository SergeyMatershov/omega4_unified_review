def _auto_collect_constants(instance, registry: ConstantsRegistry,
                            metadata: Optional[Dict[str, tuple]] = None,
                            verbose: bool = False) -> None:
    """
    Автоматически собирает все поля @dataclass и все свойства @property
    из экземпляра `instance` в `registry`.

    Параметры:
        instance:  экземпляр класса (например, C = Constants())
        registry:  реестр, куда собирать
        metadata:  словарь метаданных (level, unit, comment)
        verbose:   если True — печатать прогресс

    ПРАВИЛА:
        • Поля @dataclass → level=0 (первичные) по умолчанию
        • Свойства @property → level=1 (выведенные) по умолчанию
        • Если метаданные заданы явно — используются они
        • Если константа уже зарегистрирована вручную — НЕ перезаписывается
        • Ошибки при вычислении свойства → статус '⚠️ error',
          но регистрация всё равно происходит
    """
    if metadata is None:
        metadata = {}

    cls = type(instance)
    n_added = 0
    n_skipped = 0
    n_errors = 0

    # ------------------------------------------------------------------------
    # 1. ПОЛЯ @dataclass
    # ------------------------------------------------------------------------
    dataclass_fields = getattr(cls, '__dataclass_fields__', {})

    for name in dataclass_fields:
        if name.startswith('_'):
            continue

        if registry.get(name) is not None:
            n_skipped += 1
            continue

        try:
            value = getattr(instance, name)
        except Exception as e:
            if verbose:
                print(f"  ⚠️ {name}: ошибка чтения — {e}")
            n_errors += 1
            continue

        # Метаданные
        meta = metadata.get(name, (0, '', ''))
        level, unit, comment = (
            meta if len(meta) == 3 else (0, '', '')
        )

        if not comment:
            comment = f'Автоматически собрано из Constants.{name}'

        registry.register(
            name,
            value=value,
            unit=unit,
            level=level,
            formula=lambda v=value: v,      # константа — формула = сама себе
            formula_repr=_repr_literal(value),  # текстовое представление
            source='auto (dataclass field)',
            comment=comment,
            status='✅ auto',
        )
        n_added += 1

    # ------------------------------------------------------------------------
    # 2. СВОЙСТВА @property
    # ------------------------------------------------------------------------
    seen_properties = set()

    for klass in cls.__mro__:
        for name, attr in vars(klass).items():
            if name.startswith('_'):
                continue
            if name in seen_properties:
                continue
            if not isinstance(attr, property):
                continue
            seen_properties.add(name)

            if registry.get(name) is not None:
                n_skipped += 1
                continue

            # Вычисляем значение
            try:
                value = getattr(instance, name)
                status = '✅ auto'
            except Exception as e:
                value = None
                status = f'⚠️ error: {type(e).__name__}'
                n_errors += 1
                if verbose:
                    print(f"  ⚠️ {name}: ошибка вычисления — {e}")

            # Метаданные
            meta = metadata.get(name, (1, '', ''))
            level, unit, comment = (
                meta if len(meta) == 3 else (1, '', '')
            )

            if not comment:
                comment = f'Автоматически собрано из Constants.{name} (@property)'

            # Обёртка формулы (без аргументов, но с привязкой к instance)
            def make_formula(prop=attr, inst=instance):
                return lambda: prop.fget(inst)

            # Текстовое представление формулы (пытаемся получить из docstring)
            formula_repr = _extract_formula_from_docstring(attr, name)

            registry.register(
                name,
                value=value,
                unit=unit,
                level=level,
                formula=make_formula(),
                formula_repr=formula_repr,
                source='auto (@property)',
                comment=comment,
                status=status,
            )
            n_added += 1

    # ------------------------------------------------------------------------
    # 3. ОТЧЁТ
    # ------------------------------------------------------------------------
    if verbose:
        print("=" * 70)
        print("  АВТОСБОР КОНСТАНТ ИЗ core.py")
        print("=" * 70)
        print(f"  Добавлено:       {n_added}")
        print(f"  Пропущено (есть): {n_skipped}")
        print(f"  Ошибок:          {n_errors}")
        print(f"  Всего в REGISTRY: {len(registry)}")
        print("=" * 70)


