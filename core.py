def _repr_literal(value: Any) -> str:
    """
    Текстовое представление литерала.

    Для полей @dataclass — это просто значение.
    Для list/dict — компактная запись.
    """
    if isinstance(value, str):
        return repr(value)
    if isinstance(value, (int, float, bool)):
        return repr(value)
    if isinstance(value, (list, tuple)):
        inner = ", ".join(repr(v) for v in value)
        return f"[{inner}]"
    if isinstance(value, dict):
        inner = ", ".join(f"{repr(k)}: {repr(v)}" for k, v in value.items())
        return f"{{{inner}}}"
    return repr(value)


def _extract_formula_from_docstring(prop: property, name: str) -> str:
    """
    Попытаться извлечь формулу из docstring @property.

    Ищем строки вида:
        ФОРМУЛА: ...
        ФОРМУЛА (v78.5): ...
        V_20 = M_W · h¹¹ / rank(SU26)

    Возвращает текстовое представление или ''.
    """
    doc = prop.fget.__doc__ if prop.fget else None
    if not doc:
        return ''

    lines = doc.split('\n')
    formula_lines = []

    # Ищем секцию "ФОРМУЛА:" и следующие непустые строки до пустой
    in_formula = False
    for line in lines:
        stripped = line.strip()

        # Триггер: "ФОРМУЛА:"
        if stripped.upper().startswith('ФОРМУЛА'):
            in_formula = True
            # Может быть "ФОРМУЛА: X = Y" в одной строке
            after_colon = stripped.split(':', 1)
            if len(after_colon) > 1 and after_colon[1].strip():
                formula_lines.append(after_colon[1].strip())
            continue

        # Если в секции формулы
        if in_formula:
            if not stripped:
                # Пустая строка — конец секции
                if formula_lines:
                    break
                continue
            # Прекращаем, если началась другая секция (например, "ЗНАЧЕНИЕ:")
            if stripped.isupper() and ':' in stripped:
                break
            formula_lines.append(stripped)

    if formula_lines:
        # Убираем отступы, объединяем
        # Заменяем длинные тире и math-символы на читаемые
        result = ' '.join(formula_lines)
        # Чистим
        result = result.replace('·', '*').replace('−', '-')
        result = result.replace('⁻', '-')          # ← ДО замены цифр
        result = result.replace('⁰', '0').replace('¹', '1')
        result = result.replace('²', '2').replace('³', '3')
        result = result.replace('⁴', '4').replace('⁵', '5')
        result = result.replace('¹¹', '11').replace('¹²', '12')
        return result[:200]  # ограничим длину

    return ''
