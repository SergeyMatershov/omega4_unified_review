class HodgeNumbers:
    """Числа Ходжа CY₃ (Тянь-Яу / Z₃)."""
    
    def __init__(self, h11: Optional[int] = None, h21: Optional[int] = None):
        """
        Инициализация.
        
        Параметры:
            h11: число Ходжа h¹¹ (по умолчанию C.H11 = 6)
            h21: число Ходжа h²¹ (по умолчанию C.H21 = 9)
        """
        self.h11 = h11 if h11 is not None else C.H11
        self.h21 = h21 if h21 is not None else C.H21
    
    def compute_chi(self) -> int:
        """χ = 2(h¹¹ − h²¹)."""
        return 2 * (self.h11 - self.h21)
    
    def compute_betti(self) -> Dict[int, int]:
        """Числа Бетти для CY₃."""
        return {
            0: 1,
            1: 0,
            2: self.h11,
            3: 2 * (1 + self.h21),
            4: self.h11,
            5: 0,
            6: 1,
        }
    
    def compute_generations(self) -> int:
        """Число поколений: |χ|/2."""
        return abs(self.compute_chi()) // 2
    
    def get_full_report(self) -> Dict:
        """Полный отчёт."""
        chi = self.compute_chi()
        n_gen = self.compute_generations()
        return {
            'h11': self.h11,
            'h21': self.h21,
            'chi': chi,
            'betti': self.compute_betti(),
            'generations': n_gen,
            'verified': n_gen == C.N_GEN,
        }


