# ИСПОЛЬЗУЕТ mpmath для точного сравнения через строки.
# Это даёт точное значение 15.53 знака (не 15.46 из-за float64).
# ============================================================================

def compare_high_precision(
    a_str: str,
    b_str: str,
    fallback_a: float = None,
    fallback_b: float = None,
) -> Dict:
    """
    Сравнение двух чисел с высокой точностью через mpmath.
    
    Параметры:
        a_str: значение A как строка (50 знаков)
        b_str: значение B как строка (50 знаков)
        fallback_a: float64 fallback для A (если mpmath нет)
        fallback_b: float64 fallback для B (если mpmath нет)
    
    Возвращает:
        dict с absolute_diff, relative_diff, digits_matched
    """
    try:
        import mpmath as mp
        mp.mp.dps = 50
        
        a_mp = mp.mpf(a_str)
        b_mp = mp.mpf(b_str)
        
        diff = abs(a_mp - b_mp)
        rel = diff / abs(b_mp) if b_mp != 0 else mp.inf
        
        if diff == 0:
            digits = float('inf')
        else:
            digits = float(-mp.log10(rel))
        
        return {
            'abs_diff': float(diff),
            'rel_diff': float(rel),
            'digits_matched': digits,
            'precision': 'mpmath',
        }
    except ImportError:
        a = fallback_a if fallback_a is not None else float(a_str)
        b = fallback_b if fallback_b is not None else float(b_str)
        
        diff = abs(a - b)
        rel = diff / abs(b) if b != 0 else float('inf')
        digits = -math.log10(rel) if rel > 0 else float('inf')
        
        return {
            'abs_diff': diff,
            'rel_diff': rel,
            'digits_matched': digits,
            'precision': 'float64',
        }


