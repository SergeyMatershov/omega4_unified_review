def build_topological_chain() -> Dict:
    """
    Строит полную цепочку топологического вывода.

    СХЕМА:
        CY₃ → χ = 616, β₁₂ = 4 → n(k) → c₂ = 101 → B_i
        CY₃ → h¹¹ = 6, h²¹ = 9 → χ_Hodge = −6 → N_gen = 3
        CY₃ → ε_FN → α_GUT
        CY₃ → φ → sin²θ_W

    ВОЗВРАЩАЕТ:
        dict со всеми компонентами схемы.
    """
    # ─── Уровень 0: CY₃ ─────────────────────────────────────────────────────
    level0 = {
        'CY3': 'Тянь-Яу / Z₃',
        'h11': C.H11,       # 6
        'h21': C.H21,       # 9
    }

    # ─── Уровень 1: Топологические числа ────────────────────────────────────
    chi_hodge = 2 * (C.H11 - C.H21)    # -6
    n_gen = abs(chi_hodge) // 2        # 3
    chi = C.CHI                        # 616
    beta_12 = C.BETA_12                # 4

    level1 = {
        'chi_hodge': chi_hodge,
        'n_gen': n_gen,
        'chi': chi,
        'beta_12': beta_12,
    }

    # ─── Уровень 2: Мастер-полином ──────────────────────────────────────────
    np = MasterPolynomial.n_poly
    level2 = {
        'n(-4)': np(-4),   # 4146
        'n(-1)': np(-1),   # 8
        'n(0)': np(0),     # 0
        'n(1)': np(1),     # 26
        'n(2)': np(2),     # 4
        'n(3)': np(3),     # 58
    }

    # ─── Уровень 3: Топологические инварианты B_i ───────────────────────────
    bi_result = verify_bi_from_topology()
    level3 = {
        'c2': bi_result['c2'],
        'rank_SU26': bi_result['rank_SU26'],
        'B_1': bi_result['B1_topological'],
        'B_2': bi_result['B2_topological'],
        'B_3': bi_result['B3_topological'],
    }

    # ─── Уровень 4: Электрослабые и GUT константы ───────────────────────────
    eps_fn = C.EPS_FN
    alpha_gut = eps_fn / (4 * math.pi)
    sin2_theta_w = (3.0/8.0) / C.PHI

    level4 = {
        'eps_fn': eps_fn,
        'alpha_gut': alpha_gut,
        'sin2_theta_w': sin2_theta_w,
        'phi': C.PHI,
    }

    # ─── Уровень 5: T_CY3 ───────────────────────────────────────────────────
    tc = compute_tc_from_topology()

    return {
        'level0': level0,
        'level1': level1,
        'level2': level2,
        'level3': level3,
        'level4': level4,
        'T_CY3': tc,
    }


