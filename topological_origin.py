def verify_betti_coefficients() -> Dict:
    """
    Проверяет, что коэффициенты мастер-полинома выражаются
    через числа Бетти BSU(n).

    ФОРМУЛЫ:
        POLY_C4 = 6·β₁₂² + β₀·β₁₀ + β₀·β₁₂ + β₀
        POLY_C3 = 23·β₁₂² + β₁₀
        POLY_C2 = 6·β₁₂² + β₀ + β₀·β₁₂
        POLY_C1 = 29·β₁₂² + β₁₀·β₁₂ + β₀·β₁₀ + β₀·β₁₂

    ВОЗВРАЩАЕТ:
        dict с проверками.
    """
    b0  = BETTI_NUMBERS['BETA_0']
    b10 = BETTI_NUMBERS['BETA_10']
    b12 = BETTI_NUMBERS['BETA_12']

    checks = {
        'POLY_C4': {
            'formula': '6·β₁₂² + β₀·β₁₀ + β₀·β₁₂ + β₀',
            'computed': 6*b12**2 + b0*b10 + b0*b12 + b0,
            'expected': C.POLY_C4,
        },
        'POLY_C3': {
            'formula': '23·β₁₂² + β₁₀',
            'computed': 23*b12**2 + b10,
            'expected': C.POLY_C3,
        },
        'POLY_C2': {
            'formula': '6·β₁₂² + β₀ + β₀·β₁₂',
            'computed': 6*b12**2 + b0 + b0*b12,
            'expected': C.POLY_C2,
        },
        'POLY_C1': {
            'formula': '29·β₁₂² + β₁₀·β₁₂ + β₀·β₁₀ + β₀·β₁₂',
            'computed': 29*b12**2 + b10*b12 + b0*b10 + b0*b12,
            'expected': C.POLY_C1,
        },
    }

    for name, data in checks.items():
        data['match'] = (data['computed'] == data['expected'])

    return {
        'checks': checks,
        'all_match': all(d['match'] for d in checks.values()),
    }


def verify_bi_from_topology() -> Dict:
    """
    Проверяет, что B_i выражаются через c₂ = POLY_C2 и rank.

    ФОРМУЛЫ:
        B_1 = (2·c₂ − 5)/6
        B_2 = −c₂/6
        B_3 = −(c₂ + rank)/6

    ВОЗВРАЩАЕТ:
        dict с B_i и их сравнением с C (physics.py).
    """
    c2 = C.POLY_C2                    # 101
    # Правильно: rank(SU(26)) = 26 − 1 = 25
    # Но можно выразить через n(1):
    n1 = MasterPolynomial.n_poly(1)   # 26
    rank_SU26 = n1 - 1                 # 25

    B1_top = (2*c2 - 5) / 6
    B2_top = -c2 / 6
    B3_top = -(c2 + rank_SU26) / 6

    return {
        'c2': c2,
        'rank_SU26': rank_SU26,
        'n1': n1,
        'B1_topological': B1_top,
        'B2_topological': B2_top,
        'B3_topological': B3_top,
    }


def compute_tc_from_topology() -> Dict:
    """
    Вычисляет T_CY3 из топологии.

    ФОРМУЛА: T_CY3 = h¹¹ + n(2) = 6 + 4 = 10

    ГДЕ:
        h¹¹ = 6 — число Ходжа
        n(2) = 4 — значение мастер-полинома при k=2

    СМЫСЛ: T_CY3 — топологический период CY₃.
    """
    h11 = CY3_TOPOLOGY['h11']
    n2 = MasterPolynomial.n_poly(2)   # 4
    return {
        'h11': h11,
        'n2': n2,
        'T_CY3': h11 + n2,
    }


def verify_topology_vs_spectrum() -> Dict:
    """
    Проверка контраста «Топология vs Спектр» (Q5, v8.7).

    ЧТО ПРОВЕРЯЕТСЯ:
        • РАБОТАЕТ: B_i из топологии = (32.833, −16.833, −21.000).
        • НЕ РАБОТАЕТ: B_i из спектра SU(26) = (+16.67, +9.33, +5.67).
        • distance между ними > 40.

    ВОЗВРАЩАЕТ:
        dict с полями:
          • B_i_topo      — B_i из топологии;
          • B_i_spectrum  — B_i из спектра SU(26) (попытка, отвергнута);
          • distance      — расстояние между ними;
          • works         — True (топология работает);
          • rejected      — True (спектр отвергнут);
          • status        — 'STRUCTURAL_STRONG'.

    ИСТОЧНИК ДАННЫХ:
        • B_i_topo     — из verify_bi_from_topology().
        • B_i_spectrum — из попытки «3×26 + 3×26̄ + 675»
                         (test_beta_convention_v3.py, отвергнута).
        • dist > 40    — из q5_spectrum_derivation.py (v8.7).
    """
    # B_i из топологии (РАБОТАЕТ)
    bi_topo = verify_bi_from_topology()
    B_topo = (bi_topo['B1_topological'],
              bi_topo['B2_topological'],
              bi_topo['B3_topological'])

    # B_i из спектра SU(26) (НЕ РАБОТАЕТ, отвергнуто)
    #   Попытка: 3×26 + 3×26̄ + 675 → b_i^спектр = (+16.67, +9.33, +5.67)
    B_spectrum = (16.67, 9.33, 5.67)

    # Distance между ними
    distance = math.sqrt(sum(
        (B_topo[i] - B_spectrum[i])**2 for i in range(3)
    ))

    return {
        'B_i_topo': B_topo,
        'B_i_spectrum': B_spectrum,
        'distance': distance,
        'works': True,
        'rejected': distance > 40,
        'status': 'STRUCTURAL_STRONG',
        'note': (
            f'Топология → B_i = ({B_topo[0]:.3f}, {B_topo[1]:.3f}, '
            f'{B_topo[2]:.3f}). '
            f'Спектр SU(26) → b_i = ({B_spectrum[0]:.2f}, '
            f'{B_spectrum[1]:.2f}, {B_spectrum[2]:.2f}). '
            f'distance = {distance:.2f} > 40 — ОТВЕРГНУТО.'
        ),
    }


